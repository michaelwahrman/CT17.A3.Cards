#!/usr/bin/env python3
"""CT17 Cards - prepare face-card art from the user's prototypes.

Usage:  python3 tools/prep_art.py <prototype_dir> [out_dir]

The prototypes (ace/jack/queen/king *.webp, 816x1456) each have the index
letters and suit pips of ONE suit baked in.  This script removes those
(OpenCV inpainting) so the art can be reused for all four suits; the
game then draws its own corner index + suit pip at the same places.

Outputs (cropped to the 0.6 card aspect, 600x1000):
  jack.jpg queen.jpg king.jpg   - index/pips removed
  ace_spade.jpg                 - ace with corner indices removed (keeps the eye-spade)
  ace_blank.jpg                 - ace with corners AND the central spade removed
  eye.png                       - the eye from the ace, alpha-feathered (used on other aces + card back)
  art.js                        - all of the above as data URLs (lets index.html run from file://)
"""
import sys, os, glob, base64
import numpy as np, cv2

SRC = sys.argv[1] if len(sys.argv) > 1 else '.'
OUT = sys.argv[2] if len(sys.argv) > 2 else 'art'
os.makedirs(OUT, exist_ok=True)
W, H = 816, 1456

def load(rank):
    f = sorted(glob.glob(os.path.join(SRC, rank + '*.webp')) + glob.glob(os.path.join(SRC, rank + '*.png')) + glob.glob(os.path.join(SRC, rank + '*.jpg')))[0]
    im = cv2.imread(f, cv2.IMREAD_COLOR)
    return cv2.resize(im, (W, H), interpolation=cv2.INTER_AREA)

def boxes_mirrored(x0, y0, x1, y1):
    return [(x0, y0, x1, y1), (W - x1, H - y1, W - x0, H - y0)]

def mask_from(im, boxes, test):
    hsv = cv2.cvtColor(im, cv2.COLOR_BGR2HSV)
    m = np.zeros((H, W), np.uint8)
    sel = test(hsv).astype(np.uint8) * 255
    for (x0, y0, x1, y1) in boxes:
        m[y0:y1, x0:x1] = sel[y0:y1, x0:x1]
    m = cv2.dilate(m, np.ones((3, 3), np.uint8), iterations=4)
    return m

def red(hsv):
    h, s, v = hsv[..., 0], hsv[..., 1], hsv[..., 2]
    return ((h < 14) | (h > 165)) & (s > 70) & (v > 70)

def bright(th):
    return lambda hsv: hsv[..., 2] > th

def crop_out(im):
    # card aspect 0.6 -> 816 x 1360, centred vertically
    ch = int(W / 0.6)
    y0 = (H - ch) // 2
    return cv2.resize(im[y0:y0 + ch], (600, 1000), interpolation=cv2.INTER_AREA)

def save(name, im, q=88):
    cv2.imwrite(os.path.join(OUT, name), im, [cv2.IMWRITE_JPEG_QUALITY, q])

# J and K: red index letter, small heart, big heart (both corners)
for rank in ('jack', 'king'):
    im = load(rank)
    m = mask_from(im, boxes_mirrored(0, 20, 290, 370), red)
    im = cv2.inpaint(im, m, 9, cv2.INPAINT_TELEA)
    save(rank + '.jpg', crop_out(im))

# Q: cream letter + cream diamond on dark navy
im = load('queen')
m = mask_from(im, boxes_mirrored(36, 62, 140, 385), bright(105))
im = cv2.inpaint(im, m, 9, cv2.INPAINT_TELEA)
save('queen.jpg', crop_out(im))

# A: gold letter + spade, then central spade for the blank version
ace = load('ace')
eye_cx, eye_cy = 408, 716
eye = ace[eye_cy - 95:eye_cy + 95, eye_cx - 165:eye_cx + 165].copy()
m = mask_from(ace, boxes_mirrored(60, 92, 142, 368), bright(70))
ace = cv2.inpaint(ace, m, 9, cv2.INPAINT_TELEA)
save('ace_spade.jpg', crop_out(ace))
blank = ace.astype(np.float32)
yy, xx = np.mgrid[0:H, 0:W]
d = np.sqrt(((xx - 408) / 270.0) ** 2 + ((yy - 712) / 340.0) ** 2)
a = np.clip((1.15 - d) / 0.25, 0, 1)[..., None]          # 1 inside, feathered edge
bg = np.array([10, 9, 8], np.float32)                     # near-black of the ace
blank = blank * (1 - a) + bg * a
save('ace_blank.jpg', crop_out(blank.astype(np.uint8)))

# eye with elliptical feathered alpha
eh, ew = eye.shape[:2]
yy, xx = np.mgrid[0:eh, 0:ew]
d = np.sqrt(((xx - ew / 2) / (ew / 2)) ** 2 + ((yy - eh / 2) / (eh / 2)) ** 2)
alpha = (np.clip((1.0 - d) / 0.35, 0, 1) * 255).astype(np.uint8)
cv2.imwrite(os.path.join(OUT, 'eye.png'), np.dstack([eye, alpha]))

# art.js
parts = []
for name in ('ace_spade.jpg', 'ace_blank.jpg', 'jack.jpg', 'queen.jpg', 'king.jpg', 'eye.png'):
    mime = 'image/png' if name.endswith('png') else 'image/jpeg'
    b = base64.b64encode(open(os.path.join(OUT, name), 'rb').read()).decode()
    parts.append('  "%s": "data:%s;base64,%s"' % (name.split('.')[0], mime, b))
open(os.path.join(OUT, 'art.js'), 'w').write('// generated by tools/prep_art.py\nwindow.CT17_ART = {\n' + ',\n'.join(parts) + '\n};\n')
print('done ->', OUT)
